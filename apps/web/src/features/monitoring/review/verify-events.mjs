import { mkdtemp, readFile, writeFile, unlink, rmdir } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { call, evaluate, waitFor, click, setValue, assert, errors, ws } from './browser.mjs'

await call('Page.enable'); await call('Runtime.enable')
await call('Emulation.setDeviceMetricsOverride', { width: 1075, height: 1150, deviceScaleFactor: 1, mobile: false })
await call('Page.navigate', { url: 'http://127.0.0.1:5173/src/features/monitoring/preview/index.html' })
await waitFor(`document.querySelector('.monitoring-stats')`)
await evaluate(`document.querySelector('[aria-label="Inspect Vault events"]').click()`)
await waitFor(`document.querySelector('dialog[open]')`)
await click('Open Events Explorer')
await waitFor(`document.querySelector('.events-table')`)
await assert(`document.querySelector('.events-filters select').value === 'vault' && Array.from(document.querySelectorAll('.events-table tbody tr')).every(row => row.children[2].textContent === 'Vault')`, 'dashboard passes selected contract to explorer')
await click('Monitoring')
await waitFor(`document.querySelector('.monitoring-stats')`)
await setValue('.preview-controls label:first-of-type select', 'events')
await waitFor(`document.querySelector('.events-table')`)
await assert(`document.querySelectorAll('.events-table tbody tr').length === 10 && document.querySelector('.events-pagination').textContent.includes('248')`, 'explorer paginates 248 mock events')
const first = await evaluate(`document.querySelector('.events-table tbody time').dateTime`)
await click('Next')
await assert(`document.querySelector('.events-pagination').textContent.includes('Page 2 of 25') && document.querySelector('.events-table tbody time').dateTime !== ${JSON.stringify(first)}`, 'Next changes visible rows')
await setValue('.events-filters label:nth-child(2) select', 'Withdrawal')
await assert(`document.querySelector('.events-pagination').textContent.includes('Page 1') && Array.from(document.querySelectorAll('.events-table tbody tr')).every(row => row.children[1].textContent === 'Withdrawal')`, 'event filter resets pagination')
await setValue('.events-filters label:first-child select', 'treasury')
await assert(`document.querySelector('.monitoring-state').textContent.includes('No matching events')`, 'combined filters show no-results state')
await click('Clear filters')
await waitFor(`document.querySelector('.events-table')`)
await evaluate(`document.querySelector('.events-block-filters').open = true`)
await setValue('.events-block-filters label:first-child input', '7842300', 'input')
await setValue('.events-block-filters label:last-child input', '7842311', 'input')
await assert(`document.querySelectorAll('.events-table tbody tr').length === 4`, 'inclusive block range filters events')
await setValue('.events-block-filters label:first-child input', '7842312', 'input')
await assert(`document.querySelector('[role="alert"]').textContent.includes('Minimum block') && document.querySelector('.events-actions button').disabled`, 'reversed block range validates and disables export')
await setValue('.events-block-filters label:first-child input', '-1', 'input')
await assert(`document.querySelector('[role="alert"]').textContent.includes('non-negative')`, 'negative block numbers validate')
await click('Clear')
await setValue('.events-filters label:nth-child(3) input', '2026-10-27T00:00', 'input')
await setValue('.events-filters label:nth-child(4) input', '2026-10-26T23:59', 'input')
await assert(`document.querySelector('[role="alert"]').textContent.includes('From (UTC)')`, 'reversed UTC range validates')
await setValue('.events-filters label:nth-child(3) input', '2026-10-26T15:21', 'input')
await setValue('.events-filters label:nth-child(4) input', '2026-10-26T15:24', 'input')
await assert(`document.querySelectorAll('.events-table tbody tr').length === 2`, 'UTC date filters include the final selected minute')
await evaluate(`document.querySelector('button[aria-label^="View Transfer details"]').click()`)
await assert(`document.querySelector('.events-detail-row').textContent.includes('Decoded parameters') && document.querySelectorAll('.events-detail-row li').length === 3 && document.querySelector('.events-detail-row code').textContent.length === 66`, 'expansion shows typed parameters and full transaction hash')
await evaluate(`document.querySelector('button[aria-label^="Hide Transfer details"]').click()`)
await assert(`!document.querySelector('.events-detail-row')`, 'details collapse')
await click('Clear')
const downloadDir = await mkdtemp(join(tmpdir(), 'chainops-events-csv-'))
await call('Browser.setDownloadBehavior', { behavior: 'allow', downloadPath: downloadDir })
await click('Export CSV')
let csv = ''
for (let i = 0; i < 50; i++) {
  try { csv = await readFile(join(downloadDir, 'chainops-mock-contract-events.csv'), 'utf8'); break } catch { await new Promise(resolve => setTimeout(resolve, 100)) }
}
if (csv.split('\r\n').length !== 249 || !csv.includes('Mock fixture') || !csv.includes('Decoded Parameters')) throw new Error('CSV download content is invalid')
console.log('PASS CSV downloads all 248 filtered records with decoded parameters')
await unlink(join(downloadDir, 'chainops-mock-contract-events.csv')); await rmdir(downloadDir)
await click('Paused · mock')
await assert(`document.querySelector('.events-live').getAttribute('aria-pressed') === 'true' && document.querySelector('.monitoring-demo').textContent.includes('15 seconds')`, 'mock refresh enables explicitly labelled snapshot refresh')
await click('Live · mock')
await assert(`document.querySelector('.events-live').getAttribute('aria-pressed') === 'false'`, 'mock refresh pauses')
await call('Page.navigate', { url: 'http://127.0.0.1:5173/src/features/monitoring/preview/index.html' })
await waitFor(`document.querySelector('.monitoring-stats')`)
await setValue('.preview-controls label:first-of-type select', 'events')
await waitFor(`document.querySelector('.events-table')`)
await assert(`document.documentElement.scrollWidth <= innerWidth`, 'desktop has no page overflow')
const screenshotDir = 'apps/web/src/features/monitoring/review'
await writeFile(screenshotDir + '/events-desktop.png', Buffer.from((await call('Page.captureScreenshot', { captureBeyondViewport: true })).data, 'base64'))
await call('Emulation.setDeviceMetricsOverride', { width: 375, height: 1000, deviceScaleFactor: 1, mobile: true })
await assert(`document.documentElement.scrollWidth <= innerWidth && document.querySelector('.events-table-wrap').scrollWidth > document.querySelector('.events-table-wrap').clientWidth`, 'mobile table scrolls within the page')
await writeFile(screenshotDir + '/events-mobile.png', Buffer.from((await call('Page.captureScreenshot', { captureBeyondViewport: true })).data, 'base64'))
await setValue('.preview-controls label:last-of-type select', 'empty')
await waitFor(`document.querySelector('.monitoring-state')?.textContent.includes('No indexed events')`)
await assert(`document.querySelector('.events-actions button').disabled`, 'empty state disables CSV export')
await setValue('.preview-controls label:last-of-type select', 'error')
await waitFor(`document.querySelector('[role="alert"]')`)
await click('Try again')
await assert(`document.querySelector('[role="status"]').textContent.includes('Loading')`, 'error retry shows loading state')
await waitFor(`document.querySelector('[role="alert"]')`)
await setValue('.preview-controls label:last-of-type select', 'success')
await waitFor(`document.querySelector('.events-table')`)
if (errors.length) throw new Error(errors.join('\n'))
console.log('PASS no browser runtime errors')
ws.close()
